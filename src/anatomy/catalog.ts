/**
 * Structure catalog: metadata for every structure (available immediately for search / quiz),
 * with geometry built lazily per system by the mesh registry.
 *
 * Sources, in priority order:
 *   1. src/data/structures.json — curated records (spec data model) overriding generated text
 *   2. procedural builders in ./systems/*
 *   3. structures discovered in external GLBs (see meshRegistry.loadGlbSystem)
 */
import type { Sex, StructureDef, StructureRecord, SystemId } from '../types';
import curated from '../data/structures.json';
import { buildSkeletal } from './systems/skeletal';
import { buildMuscular } from './systems/muscular';
import { buildNervous } from './systems/nervous';
import { buildCardiovascular } from './systems/cardiovascular';
import { buildDigestive, buildRespiratory, buildReproductive, buildUrinary } from './systems/visceral';
import { buildLymphatic, buildSkin } from './systems/lymphaticSkin';

const BUILDERS: Record<SystemId, (sex: Sex) => StructureDef[]> = {
  skeletal: () => buildSkeletal(),
  muscular: () => buildMuscular(),
  nervous: () => buildNervous(),
  cardiovascular: () => buildCardiovascular(),
  respiratory: () => buildRespiratory(),
  digestive: () => buildDigestive(),
  urinary: () => buildUrinary(),
  lymphatic: () => buildLymphatic(),
  reproductive: () => buildReproductive(),
  integumentary: (sex) => buildSkin(sex),
};

const CURATED = new Map((curated as StructureRecord[]).map((r) => [r.id, r]));

/**
 * Catalog generated by scripts/build-models.ts for a sex whose body comes from real GLB models
 * (public/models/<sex>/catalog.json). When present it replaces the procedural catalog; geometry
 * then streams from the GLB files instead of `build()`.
 */
const external = new Map<Sex, (StructureRecord & { kind: StructureDef['kind'] })[]>();
export function setExternalCatalog(sex: Sex, records: (StructureRecord & { kind: StructureDef['kind'] })[]) {
  external.set(sex, records);
  cache.delete(sex);
}
const glbOnly = (): never => {
  throw new Error('Geometry for this structure is streamed from a GLB model');
};

interface Catalog {
  list: StructureDef[];
  byId: Map<string, StructureDef>;
  bySystem: Map<SystemId, StructureDef[]>;
}
const cache = new Map<Sex, Catalog>();

export function getCatalog(sex: Sex): Catalog {
  let c = cache.get(sex);
  if (c) return c;
  const list: StructureDef[] = [];
  const bySystem = new Map<SystemId, StructureDef[]>();
  const ext = external.get(sex);
  if (ext) {
    for (const r of ext) {
      const d: StructureDef = { ...r, build: glbOnly };
      list.push(d);
      if (!bySystem.has(d.system)) bySystem.set(d.system, []);
      bySystem.get(d.system)!.push(d);
    }
    for (const sys of Object.keys(BUILDERS) as SystemId[]) if (!bySystem.has(sys)) bySystem.set(sys, []);
    c = { list, byId: new Map(list.map((d) => [d.id, d])), bySystem };
    cache.set(sex, c);
    return c;
  }
  for (const [sys, build] of Object.entries(BUILDERS) as [SystemId, (s: Sex) => StructureDef[]][]) {
    const defs = build(sex)
      .filter((d) => d.sex === 'both' || d.sex === sex)
      .map((d) => {
        const o = CURATED.get(d.id);
        return o ? { ...d, ...o, facts: { ...d.facts, ...o.facts }, build: d.build, kind: d.kind } : d;
      });
    bySystem.set(sys, defs);
    list.push(...defs);
  }
  c = { list, byId: new Map(list.map((d) => [d.id, d])), bySystem };
  cache.set(sex, c);
  return c;
}

export const getStructure = (sex: Sex, id: string | null | undefined) => (id ? getCatalog(sex).byId.get(id) : undefined);

/** Register a structure discovered in an external GLB that has no procedural counterpart. */
export function registerExternal(sex: Sex, def: StructureDef) {
  const c = getCatalog(sex);
  if (c.byId.has(def.id)) return;
  c.list.push(def);
  c.byId.set(def.id, def);
  c.bySystem.get(def.system)?.push(def);
}

/** Plain JSON records (spec data model) for export. */
export function exportRecords(sex: Sex): StructureRecord[] {
  return getCatalog(sex).list.map(({ build: _b, kind: _k, ...rec }) => rec);
}
